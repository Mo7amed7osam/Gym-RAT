#!/usr/bin/env node
/**
 * Copies the exactly-mapped RepDB free-tier stills into assets/exercise-media,
 * records sha256 + dimensions + licence per file, and regenerates the manifest,
 * the Metro require() index and the coverage report.
 *
 *   node scripts/media/import-repdb.mjs <path-to-exercise-dataset-checkout>
 *
 * Only ids listed in repdb-mapping.json "matched" are read. Nothing else from
 * the dataset is copied (licence term 3: no redistribution as a dataset).
 * Images are copied unmodified (term 4 allows resize/crop/recolour only).
 */
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('../..', import.meta.url)));
const mappingPath = join(root, 'scripts/media/repdb-mapping.json');
const outDir = join(root, 'assets/exercise-media');
const datasetDir = process.argv[2];
if (!datasetDir) {
  console.error('usage: import-repdb.mjs <exercise-dataset checkout>');
  process.exit(2);
}
const mapping = JSON.parse(readFileSync(mappingPath, 'utf8'));
const dataset = JSON.parse(readFileSync(join(datasetDir, 'exercises.json'), 'utf8'));
const byId = new Map(dataset.exercises.map((e) => [e.id, e]));

/** WebP (RIFF) dimensions: VP8 (lossy), VP8L (lossless) and VP8X (extended). */
function webpSize(buf) {
  if (buf.toString('ascii', 0, 4) !== 'RIFF' || buf.toString('ascii', 8, 12) !== 'WEBP') throw new Error('not a WebP file');
  const chunk = buf.toString('ascii', 12, 16);
  if (chunk === 'VP8 ') return { width: buf.readUInt16LE(26) & 0x3fff, height: buf.readUInt16LE(28) & 0x3fff };
  if (chunk === 'VP8L') {
    const b = buf.readUInt32LE(21);
    return { width: (b & 0x3fff) + 1, height: ((b >> 14) & 0x3fff) + 1 };
  }
  if (chunk === 'VP8X') return { width: buf.readUIntLE(24, 3) + 1, height: buf.readUIntLE(27, 3) + 1 };
  throw new Error(`unknown WebP chunk ${chunk}`);
}

mkdirSync(outDir, { recursive: true });
for (const f of readdirSync(outDir)) if (f.endsWith('.webp')) rmSync(join(outDir, f));

const entries = {};
for (const [exerciseId, repdbId] of Object.entries(mapping.matched)) {
  const e = byId.get(repdbId);
  if (!e) throw new Error(`RepDB id ${repdbId} (for ${exerciseId}) not in dataset`);
  const flat = e.images?.flat ?? {};
  const files = {};
  for (const role of ['start', 'peak', 'main']) {
    if (!flat[role]) continue;
    const src = join(datasetDir, flat[role]);
    const name = `${exerciseId}-${role === 'peak' ? 'end' : role}.webp`;
    copyFileSync(src, join(outDir, name));
    const buf = readFileSync(join(outDir, name));
    files[role === 'peak' ? 'end' : role] = { file: name, sha256: createHash('sha256').update(buf).digest('hex'), ...webpSize(buf), bytes: buf.length };
  }
  entries[exerciseId] = {
    kind: files.start && files.end ? 'still_pair' : 'still_single',
    source: 'repdb',
    sourceId: repdbId,
    sourceName: e.name_en,
    license: mapping.source.license,
    attribution: mapping.source.attribution,
    files,
  };
}
for (const [exerciseId, info] of Object.entries(mapping.unmatched)) {
  entries[exerciseId] = { kind: 'none', source: null, nearest: info.nearest, reason: info.reason };
}

const manifest = {
  generatedBy: basename(fileURLToPath(import.meta.url)),
  generatedAt: new Date().toISOString(),
  source: mapping.source,
  entries: Object.fromEntries(Object.entries(entries).sort(([a], [b]) => a.localeCompare(b))),
};
writeFileSync(join(outDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);

// Metro needs literal require() calls.
const lines = [
  '// GENERATED by scripts/media/import-repdb.mjs — do not edit by hand.',
  "import type { ImageSourcePropType } from 'react-native';",
  '',
  'export const EXERCISE_MEDIA_FILES = {',
];
for (const [id, entry] of Object.entries(manifest.entries)) {
  if (entry.kind === 'none') continue;
  const parts = Object.entries(entry.files).map(([role, f]) => `${role}: require('./${f.file}')`);
  lines.push(`  ${id}: { ${parts.join(', ')} },`);
}
lines.push('} satisfies Record<string, Record<string, ImageSourcePropType>>;', '');
writeFileSync(join(outDir, 'index.ts'), `${lines.join('\n')}`);

const matched = Object.values(entries).filter((e) => e.kind !== 'none').length;
const total = Object.keys(entries).length;
const report = [
  '# Exercise illustration coverage',
  '',
  `Generated ${manifest.generatedAt} from RepDB commit ${mapping.source.commit}.`,
  '',
  `**${matched} of ${total} built-in exercises** have exact RepDB start/end stills (${((matched / total) * 100).toFixed(0)}%). The rest show the labelled "No illustration" card.`,
  '',
  '## Matched',
  '| Gym RAT id | RepDB id | RepDB name | files |',
  '|---|---|---|---|',
  ...Object.entries(manifest.entries)
    .filter(([, e]) => e.kind !== 'none')
    .map(([id, e]) => `| ${id} | ${e.sourceId} | ${e.sourceName} | ${Object.keys(e.files).join(' + ')} |`),
  '',
  '## Unmatched (fallback card)',
  '| Gym RAT id | nearest RepDB variant | why it was rejected |',
  '|---|---|---|',
  ...Object.entries(manifest.entries)
    .filter(([, e]) => e.kind === 'none')
    .map(([id, e]) => `| ${id} | ${e.nearest} | ${e.reason} |`),
  '',
  `Licence: ${mapping.source.license}. Attribution shown in Settings → About: "${mapping.source.attribution}". Images copied unmodified; no upscaling, background removal or generative derivation.`,
  '',
];
writeFileSync(join(outDir, 'COVERAGE.md'), report.join('\n'));
console.log(`matched ${matched}/${total}; wrote manifest.json, index.ts, COVERAGE.md and ${Object.values(entries).reduce((n, e) => n + Object.keys(e.files ?? {}).length, 0)} images`);
